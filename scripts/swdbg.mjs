const s = w.strands[0];
console.log('n', s.particles.length, 'rest', s.totalRest().toFixed(2), 'last3', s.particles.slice(-3).map(p => `(${p.x.toFixed(2)},${p.y.toFixed(2)} w${p.w.toFixed(1)} ${p.pin?.kind})`).join(' '));
w.releaseOlive();
let f = 0;
run(w, 1, (w) => { if (f++ % 5 === 0) { const s = w.strands[0]; const L = s.particles.at(-1); console.log(w.time.toFixed(2), 'olive', w.olive.x.toFixed(2), w.olive.y.toFixed(2), 'v', w.olive.vx.toFixed(2), w.olive.vy.toFixed(2), 'end', L.x.toFixed(2), L.y.toFixed(2), 'restTot', s.totalRest().toFixed(2), 'strain', Math.max(...s.strain).toFixed(3), 'T', s.T.toFixed(2)); } });
